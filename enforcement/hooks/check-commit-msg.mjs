#!/usr/bin/env node
/**
 * commit-msg hook — enforces Conventional Commits per standards/reference/git-pr.md.
 *
 * Also blocks attribution trailers, which standards/core/guardrails.md forbids
 * outright. A prose rule can be misread by an agent; this cannot.
 *
 * Usage: node check-commit-msg.mjs <path-to-commit-msg-file>
 */

import { readFileSync } from 'node:fs';

const TYPES = ['feat', 'fix', 'chore', 'refactor', 'test', 'docs', 'perf', 'ci', 'build', 'revert'];
const PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([\\w./-]+\\))?!?: .{1,}`);
const VAGUE = /^(wip|fix|update|changes|stuff|asdf|temp|test)\.?$/i;
const ATTRIBUTION = /^(co-authored-by|generated[- ]with|assisted[- ]by):/im;

const path = process.argv[2];
if (!path) process.exit(0);

let msg;
try {
  msg = readFileSync(path, 'utf8');
} catch {
  process.exit(0);
}

// Ignore comments and anything git appends below the scissors line.
const lines = msg.split('\n').filter((l) => !l.startsWith('#'));
const subject = (lines[0] ?? '').trim();
const body = lines.join('\n');

const fail = (reason, hint) => {
  console.error(`\nCommit message rejected: ${reason}\n\n  "${subject}"\n\n${hint}\n`);
  process.exit(1);
};

if (!subject) fail('empty subject', 'Write type(scope): description');

// Merge and revert commits are generated by git; leave them alone.
if (/^(Merge|Revert)\s/.test(subject)) process.exit(0);

if (ATTRIBUTION.test(body)) {
  fail(
    'contains an attribution trailer',
    'standards/core/guardrails.md forbids Co-Authored-By, generated-with, and\n' +
      'assisted-by trailers. Remove it.'
  );
}

if (VAGUE.test(subject)) {
  fail('too vague to be useful', 'Say what changed and why. See standards/reference/git-pr.md.');
}

if (!PATTERN.test(subject)) {
  fail(
    'not a Conventional Commit',
    `Expected: type(scope): description\nTypes: ${TYPES.join(', ')}\n` +
      'Example: fix(cart): keep filter state across page change'
  );
}

if (subject.length > 72) {
  fail(`subject is ${subject.length} chars`, 'Keep it under 72. Detail goes in the body.');
}
